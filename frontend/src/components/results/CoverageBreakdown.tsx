/**
 * Extracts coverage items from either result.statistics/evidence breakdown,
 * or by parsing text in the assistant response (e.g. "Estimated image coverage: 62279 pixels (4.05%) water...").
 * Preserves the exact values generated by the backend without recalculation.
 */
export function extractCoverageItems(
  result?: AnalysisResponse | null,
  rawText?: string
): CoverageItem[] {
  const itemsMap: Map<string, CoverageItem> = new Map();

  // 1. Try to pull structured breakdown from result.statistics.land_cover
  const stats = (result?.statistics?.land_cover || {}) as Record<string, any>;
  const breakdown = (stats.breakdown || {}) as Record<string, any>;

  // Check evidence if not in statistics
  let evidenceBreakdown: Record<string, any> = {};
  if (result?.evidence) {
    for (const ev of result.evidence) {
      if (
        (ev.kind.includes("land_cover") || ev.kind.includes("landcover") || ev.kind.includes("scene_description")) &&
        ev.metrics?.breakdown &&
        typeof ev.metrics.breakdown === "object"
      ) {
        evidenceBreakdown = ev.metrics.breakdown as Record<string, any>;
        break;
      }
    }
  }

  const combinedBreakdown = { ...evidenceBreakdown, ...breakdown };

  if (Object.keys(combinedBreakdown).length > 0) {
    for (const [rawKey, val] of Object.entries(combinedBreakdown)) {
      if (!val || typeof val !== "object") continue;
      const keyNorm = rawKey.toLowerCase().trim().replace(/\s+/g, "_");
      const config = CATEGORY_CONFIG[keyNorm] || CATEGORY_CONFIG[rawKey.toLowerCase()] || {
        name: rawKey.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
        color: val.color || "#64748b",
        icon: (s = 14) => <Layers size={s} />,
      };

      const px = typeof val.pixels === "number" ? val.pixels : (typeof val.pixel_count === "number" ? val.pixel_count : null);
      const pct = typeof val.percent === "number" ? val.percent : null;

      if (px !== null || pct !== null) {
        itemsMap.set(config.name.toLowerCase(), {
          id: keyNorm,
          name: config.name,
          pixels: px ?? 0,
          percent: pct ?? 0,
          formattedPixels: px !== null ? px.toLocaleString() : "—",
          formattedPercent: pct !== null ? `${pct.toFixed(2)}%` : "—",
          color: config.color,
          icon: config.icon(13),
        });
      }
    }
  }

  // 2. Parse text if coverage list was in rawText or verdict.answer
  // Examples:
  // "Estimated image coverage: 62279 pixels (4.05%) water, 0 pixels (0.00%) vegetation, 277483 pixels (18.07%) built up, ..."
  // "water 62279 pixels (4.05%), vegetation 0 pixels (0.00%)..."
  const textToScan = [rawText, result?.verdict?.answer, stats.summary].filter(Boolean).join(" ");
  if (textToScan) {
    // Pattern A: "62279 pixels (4.05%) water"
    const patternA = /(\d[\d,]*)\s*pixels?\s*\(([\d.]+)%\)\s*([a-zA-Z\s_-]+?)(?=[,;.]|\s*(?:and\s+)?\d[\d,]*\s*pixels?|$)/gi;
    let match: RegExpExecArray | null;
    while ((match = patternA.exec(textToScan)) !== null) {
      const pxStr = match[1].replace(/,/g, "");
      const pctStr = match[2];
      const categoryRaw = match[3].trim().toLowerCase();

      const px = parseInt(pxStr, 10);
      const pct = parseFloat(pctStr);
      const keyNorm = categoryRaw.replace(/[\s-]+/g, "_");

      const config = CATEGORY_CONFIG[keyNorm] || CATEGORY_CONFIG[categoryRaw] || {
        name: categoryRaw.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
        color: "#64748b",
        icon: (s = 14) => <Layers size={s} />,
      };

      if (!isNaN(px) && !isNaN(pct)) {
        itemsMap.set(config.name.toLowerCase(), {
          id: keyNorm,
          name: config.name,
          pixels: px,
          percent: pct,
          formattedPixels: px.toLocaleString(),
          formattedPercent: `${pct.toFixed(2)}%`,
          color: config.color,
          icon: config.icon(13),
        });
      }
    }

    // Pattern B: "water: 62279 pixels (4.05%)" or "water 62279 pixels (4.05%)"
    if (itemsMap.size === 0) {
      const patternB = /([a-zA-Z\s_-]+?)\s*(?::\s*)?(\d[\d,]*)\s*pixels?\s*\(([\d.]+)%\)/gi;
      while ((match = patternB.exec(textToScan)) !== null) {
        const categoryRaw = match[1].trim().toLowerCase();
        // Ignore words like "estimated", "covers"
        if (/^(estimated|covers|unclassified|total|valid|image)/i.test(categoryRaw)) continue;

        const pxStr = match[2].replace(/,/g, "");
        const pctStr = match[3];
        const px = parseInt(pxStr, 10);
        const pct = parseFloat(pctStr);
        const keyNorm = categoryRaw.replace(/[\s-]+/g, "_");

        const config = CATEGORY_CONFIG[keyNorm] || CATEGORY_CONFIG[categoryRaw] || {
          name: categoryRaw.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
          color: "#64748b",
          icon: (s = 14) => <Layers size={s} />,
        };

        if (!isNaN(px) && !isNaN(pct)) {
          itemsMap.set(config.name.toLowerCase(), {
            id: keyNorm,
            name: config.name,
            pixels: px,
            percent: pct,
            formattedPixels: px.toLocaleString(),
            formattedPercent: `${pct.toFixed(2)}%`,
            color: config.color,
            icon: config.icon(13),
          });
        }
      }
    }
  }

  // Convert map to array, prioritizing non-zero or dominant categories first
  const list = Array.from(itemsMap.values());
  list.sort((a, b) => {
    // Non-unknown non-zero first
    if (a.id === "unknown") return 1;
    if (b.id === "unknown") return -1;
    return b.percent - a.percent;
  });

  return list;
}

/**
 * Strips the long, clunky coverage sentence from text paragraphs
 * so the conversational prose remains clean and readable.
 */
export function cleanLongCoverageText(text: string): string {
  if (!text) return text;
  // Match "Estimated image coverage: 62279 pixels ... [up to end of sentence or paragraph]"
  let cleaned = text.replace(
    /(?:Estimated\s+(?:image\s+)?coverage|Estimated\s+classes):?\s*(?:\d[\d,]*\s*pixels?\s*\([\d.]+%\)[^.]*?\.)/gi,
    ""
  );
  // Match "Estimated classes: water 62279 pixels (4.05%), ... ."
  cleaned = cleaned.replace(
    /Estimated\s+classes:\s*[^.]*\./gi,
    ""
  );
  return cleaned.trim();
}

interface CoverageBreakdownProps {
  result: AnalysisResponse;
  rawText?: string;
  className?: string;
}

export const CoverageBreakdown: React.FC<CoverageBreakdownProps> = ({
  result,
  rawText,
  className = "",
}) => {
  const items = useMemo(() => extractCoverageItems(result, rawText), [result, rawText]);

  // If no items were extracted or not a land-cover analysis with breakdown, do not render
  if (items.length === 0) {
    return null;
  }

  return (
    <div className={`coverage-breakdown-card ${className}`}>
      <div className="coverage-breakdown-header">
        <div className="coverage-breakdown-title-wrap">
          <PieChart size={14} className="coverage-header-icon" />
          <h4 className="coverage-breakdown-title">Land-Cover Summary</h4>
        </div>
        <span className="coverage-category-count">{items.length} classes</span>
      </div>

      <div className="coverage-breakdown-grid">
        {items.map((item) => {
          const isZero = item.pixels === 0 && item.percent === 0;
          return (
            <div
              key={item.id}
              className={`coverage-cell ${isZero ? "zero-coverage" : ""}`}
              title={`${item.name}: ${item.formattedPixels} pixels (${item.formattedPercent})`}
            >
              <div className="coverage-cell-top">
                <span
                  className="coverage-swatch-dot"
                  style={{ backgroundColor: item.color }}
                />
                <span className="coverage-name">{item.name}</span>
                <span className="coverage-percent">{item.formattedPercent}</span>
              </div>

              <div className="coverage-bar-track">
                <div
                  className="coverage-bar-fill"
                  style={{
                    width: `${Math.min(100, Math.max(0, item.percent))}%`,
                    backgroundColor: item.color,
                  }}
                />
              </div>

              <div className="coverage-pixels-sub">
                <span>{item.formattedPixels} px</span>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};

export default CoverageBreakdown;
